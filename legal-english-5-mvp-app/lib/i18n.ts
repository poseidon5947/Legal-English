export const messages = { en, es };
export type MessageKey = keyof typeof en;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let text = messages[locale][key] || messages.en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function categoryLabel(locale: Locale, category: string) {
  if (category === "Corporate Law") return translate(locale, "catCorporate");
  if (category === "Contracts") return translate(locale, "catContracts");
  if (category === "Employment Law") return translate(locale, "catEmployment");
  if (category === "All") return translate(locale, "all");
  return category;
}

export function stateLabel(locale: Locale, state: string) {
  if (state === "learning") return translate(locale, "stateLearning");
  if (state === "mastered") return translate(locale, "stateMastered");
  return translate(locale, "stateNew");
}

export function entitlementLabel(locale: Locale, label: string) {
  const map: Record<string, MessageKey> = {
    "Trial active": "entitlementTrial",
    "Subscription active": "entitlementActive",
    "Exceptional access": "entitlementGrant",
    "Payment failed": "entitlementFailed",
    "Payment pending": "entitlementPending",
    "Subscription cancelled": "entitlementCancelled",
    "Trial expired": "entitlementExpired",
    "Access blocked": "entitlementBlocked",
    "Sign in required": "entitlementSignIn",
  };
  return map[label] ? translate(locale, map[label]) : label;
}
